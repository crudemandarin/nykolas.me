// Earth and the Moon for the hero sky (docs/claude/handoffs/EARTH-ICON-HANDOFF.md, EARTH-SPIN-HANDOFF.md).
//   node brand/round-2-iconography/gen_earth.mjs     (Node >= 22.6; strips TS types natively on 23.6+)
// 1. Bakes a low-detail coastline into earth-art.ts (between the <land> markers): Natural Earth 110m land
//    (world-atlas, already a site dependency), coarsened on the sphere and with small islands dropped, so the
//    spinning hero Earth stays put frame to frame. Greenland is kept apart as ice.
// 2. Writes the static nyko-earth.svg (resting pose) from earth-art.ts, nyko-moon.svg, public/brand copies,
//    and qa/earth-moon-qa.svg (sizes, lit/unlit, Night/Day, plus a rotation strip).
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { geoArea, geoContains, geoDistance } from 'd3-geo';
import { feature } from 'topojson-client';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const MODULE = join(HERE, 'earth-art.ts');
const put = (p, s) => { writeFileSync(p, s); console.log('wrote', p.slice(ROOT.length + 1)); };

// ── 1. bake the coastline ─────────────────────────────────────────
const STEP = 3.5 * Math.PI / 180;      // keep a point only once it's 3.5° from the last kept one (~3.7 units at r60)
const MIN_AREA = 0.0035;               // steradians (~140,000 km²): keeps Great Britain, Honshu, New Zealand; drops the rest
const GREENLAND = [-42, 72];
const r1 = (v) => Math.round(v * 10) / 10;
function coarsen(ring) {
  const out = [];
  for (const q of ring) if (!out.length || geoDistance(q, out.at(-1)) >= STEP) out.push(q);
  while (out.length > 3 && geoDistance(out[0], out.at(-1)) < STEP) out.pop();
  return out.length >= 3 ? [...out, out[0]].map(([a, b]) => [r1(a), r1(b)]) : null;
}
const topo = JSON.parse(readFileSync(join(ROOT, 'node_modules/world-atlas/land-110m.json'), 'utf8'));
const land = [], ice = [];
for (const f of feature(topo, topo.objects.land).features) {
  for (const rings of f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates]) {
    const g = { type: 'Polygon', coordinates: rings };
    if (geoArea(g) < MIN_AREA) continue;
    const kept = rings.map((r, i) => (i && geoArea({ type: 'Polygon', coordinates: [r] }) > 4 * Math.PI - MIN_AREA ? null : coarsen(r))).filter(Boolean);
    if (!kept.length) continue;
    const a = geoArea({ type: 'Polygon', coordinates: kept });
    if (a > 2 * Math.PI) throw new Error('coarsened polygon flipped winding');
    (geoContains(g, GREENLAND) ? ice : land).push(kept);
  }
}
const block = `// <land> generated by brand/round-2-iconography/gen_earth.mjs from world-atlas land-110m (Natural Earth, public domain)
const LAND: Poly[] = ${JSON.stringify(land)};
const ICE: Poly[] = ${JSON.stringify(ice)};
// </land>`;
const src = readFileSync(MODULE, 'utf8').replace(/\/\/ <land>[\s\S]*?\/\/ <\/land>/, () => block);
put(MODULE, src);
console.log(`  ${land.length} land polygons, ${ice.length} ice, ${land.flat(2).length + ice.flat(2).length} points`);

// ── 2. static Earth (resting pose) from the module ─────────────────
const { earthSvg: earthAt, EARTH } = await import(pathToFileURL(MODULE).href + `?t=${Date.now()}`);
const MOON = '#C9CFDE', MOON_HI = '#DDE2EC', MARE = '#9AA4BE';
const COMMENT = `<!--
  NYKO Earth (hero sky), resting pose. Origin (0,0) = centre; disc radius 60, nothing outside it. Clip to r=60 in code.
  Unlit: no terminator, night side or specular. The site shades it from the sun's direction (shadeFrom) and
  draws the atmosphere halo. Orthographic view centred ${EARTH.LAT}°N ${Math.abs(EARTH.REST_LON)}°W (North America; Seattle upper-left).
  Land: Natural Earth 110m (public domain), coarsened. Source: brand/round-2-iconography/earth-art.ts
  (earthLayers(lon) gives the same art at any rotation), written by gen_earth.mjs.
  Groups, back to front: ocean, grid, land, ice (Arctic cap + Greenland), clouds. Low detail, rounded edges.
-->
`;
const earthSvg = earthAt(EARTH.REST_LON, COMMENT);

// ── Moon (near side, simplified maria) ───────────────────────────
// Ellipses in disc units (r = 15), x right, y down, as seen from the northern hemisphere.
const MARIA = [
  // Oceanus Procellarum + Imbrium: one large western mass
  [-8.4, 0.6, 3.2, 6.4, 8], [-5.6, -4.6, 4.4, 3.8, 0], [-6.2, 3.4, 3.0, 3.4, -10],
  // Serenitatis, Tranquillitatis
  [1.6, -4.8, 2.7, 2.5, 0], [4.0, -1.2, 3.4, 2.6, -20],
  // Crisium (the isolated oval near the eastern limb)
  [10.4, -3.4, 1.9, 1.6, 0],
  // Fecunditatis, Nubium (small round ones left out: they read as crater holes)
  [7.4, 2.0, 1.9, 2.8, 10], [-2.4, 6.2, 2.8, 1.9, 0],
];
const f = (v) => +v.toFixed(2);
const moonSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-16 -16 32 32" width="128" height="128"><title>NYKO Moon</title>
<!--
  NYKO Moon (hero sky). Origin (0,0) = centre; disc radius 15. Near side, north up, simplified maria.
  Unlit: the site shades the phase from the sun's direction. Source: brand/round-2-iconography/gen_earth.mjs.
-->
<defs>
  <linearGradient id="moon-face" x1="-11" y1="-11" x2="11" y2="11" gradientUnits="userSpaceOnUse">
    <stop offset="0" stop-color="${MOON_HI}"/><stop offset="1" stop-color="${MOON}"/>
  </linearGradient>
</defs>
<circle r="15" fill="url(#moon-face)"/>
<g id="maria" fill="${MARE}">${MARIA.map(([x, y, rx, ry, a]) => `<ellipse cx="${f(x)}" cy="${f(y)}" rx="${f(rx)}" ry="${f(ry)}"${a ? ` transform="rotate(${a} ${f(x)} ${f(y)})"` : ''}/>`).join('')}</g>
</svg>
`;

put(join(HERE, 'nyko-earth.svg'), earthSvg);
put(join(HERE, 'nyko-moon.svg'), moonSvg);
put(join(ROOT, 'public/brand/nyko-earth.svg'), earthSvg);
put(join(ROOT, 'public/brand/nyko-moon.svg'), moonSvg);

// ── QA sheet: Earth 30/48/72, Moon 8/20, raw and as the site will shade them, Night and Day ──
const b64 = (s) => `data:image/svg+xml;base64,${Buffer.from(s).toString('base64')}`;
const img = (s, x, y, px) => `<image x="${x - px / 2}" y="${y - px / 2}" width="${px}" height="${px}" href="${b64(s)}"/>`;
// Approximation of the site's shadeFrom(): night side away from a sun to the upper right.
let gid = 0;
const shade = (x, y, r, strength) => {
  const id = `sh${gid++}`, dx = Math.cos(-0.6) * r, dy = Math.sin(-0.6) * r;
  return `<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${x + dx * 0.4}" y1="${y + dy * 0.4}" x2="${x - dx}" y2="${y - dy}">
<stop offset="0" stop-color="#0A0D18" stop-opacity="0"/><stop offset="0.3" stop-color="#0A0D18" stop-opacity="0.15"/><stop offset="1" stop-color="#0A0D18" stop-opacity="${strength}"/></linearGradient>
<circle cx="${x}" cy="${y}" r="${r}" fill="url(#${id})"/>`;
};
const halo = (x, y, r) => `<radialGradient id="h${gid}" gradientUnits="userSpaceOnUse" cx="${x}" cy="${y}" r="${r * 1.28}">
<stop offset="${0.9 / 1.28}" stop-color="#7CC4FF" stop-opacity="0.45"/><stop offset="1" stop-color="#7CC4FF" stop-opacity="0"/></radialGradient>
<circle cx="${x}" cy="${y}" r="${r * 1.28}" fill="url(#h${gid++})"/>`;
const W = 900, rowH = 180, spinH = 130;
let body = '';
[['#0F1220', 0.88, 0.8], ['#F2F4F8', 0.6, 0.5]].forEach(([bg, es, ms], t) => {
  const y0 = t * rowH * 2;
  body += `<rect y="${y0}" width="${W}" height="${rowH * 2}" fill="${bg}"/>`;
  [[0, false], [1, true]].forEach(([row, lit]) => {
    const y = y0 + row * rowH + rowH / 2;
    let x = 60;
    for (const px of [30, 48, 72, 160]) {
      const r = (px * 60) / 128 * (128 / 120);      // disc radius on screen (the disc is 120 of the 128 viewBox)
      if (lit) body += halo(x, y, r);
      body += img(earthSvg, x, y, (px * 128) / 120);
      if (lit) body += shade(x, y, r, es);
      x += px / 2 + 70 + (px >= 72 ? 60 : 0);
    }
    x += 40;
    for (const px of [8, 20, 60]) {
      body += img(moonSvg, x, y, (px * 32) / 30);
      if (lit) body += shade(x, y, px / 2, ms);
      x += px / 2 + 50;
    }
  });
});
// Rotation strip: a full turn in 8 steps at 72px, lit, on Night. The grid and coastline must hold still between steps.
const y0 = rowH * 4;
body += `<rect y="${y0}" width="${W}" height="${spinH}" fill="#0F1220"/>`;
for (let i = 0; i < 8; i++) {
  const x = 60 + i * 110, y = y0 + spinH / 2, r = 36;
  body += halo(x, y, r) + img(earthAt(EARTH.REST_LON - i * 45), x, y, (72 * 128) / 120) + shade(x, y, r, 0.88);
}
mkdirSync(join(HERE, 'qa'), { recursive: true });
put(join(HERE, 'qa', 'earth-moon-qa.svg'), `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${rowH * 4 + spinH}" viewBox="0 0 ${W} ${rowH * 4 + spinH}"><defs/>${body}</svg>\n`);
