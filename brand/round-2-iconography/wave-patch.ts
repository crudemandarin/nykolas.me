const f = (v: number) => String(Math.round(v * 100) / 100);

function rockPath(x: number, y: number, r: number, k: number): string {
  // deterministic lumpy heptagon; k varies the outline per slot
  const out: string[] = [];
  for (let i = 0; i < 7; i++) {
    const a = (i / 7) * Math.PI * 2 + k * 0.7;
    const rr = r * (0.78 + 0.3 * Math.abs(Math.sin(k * 3.1 + i * 2.3)));
    out.push(`${f(x + rr * Math.cos(a))},${f(y + rr * Math.sin(a))}`);
  }
  return `M ${out.join(' L ')} Z`;
}

function starPath(cx: number, cy: number, R: number, rot: number): string {
  const r = R * 0.45, out: string[] = [];
  for (let i = 0; i < 10; i++) {
    const a = ((rot - 90 + i * 36) * Math.PI) / 180, rr = i % 2 ? r : R;
    out.push(`${f(cx + rr * Math.cos(a))},${f(cy + rr * Math.sin(a))}`);
  }
  return `M ${out.join(' L ')} Z`;
}

function cross(x: number, y: number, s: number): string {
  return `<path d="M ${x - s},${y} H ${x + s} M ${x},${y - s} V ${y + s}" stroke="${HULL_M}" stroke-width="2.2" stroke-linecap="round" fill="none"/>`;
}

function textPath(s: string, size: number, tracking: number): [string, number] {
  const scale = size / UPEM;
  let x = 0, out = '';
  for (const ch of s) {
    const g = GLYPHS[ch];
    if (!g) { x += 600 * scale + tracking * size; continue; }
    if (g[1]) out += `<path transform="translate(${f(x)} 0) scale(${scale.toFixed(6)} ${(-scale).toFixed(6)})" d="${g[1]}"/>`;
    x += g[0] * scale + tracking * size;
  }
  return [out, x - tracking * size];
}

// A layer is drawn in colour, and in the 1-bit twin either inked (white in the mask), cut (black) or skipped.
type Layer = { svg: string; bit?: 'ink' | 'cut' | 'skip'; bitSvg?: string };

export type WavePatch = { wave: number; code: string; tier: number; stars: number; color: string; onebit: string };

export function wavePatch(waveIn: number): WavePatch {
  const wave = Math.max(1, Math.floor(waveIn));
  const tier = waveTier(wave), stars = waveStars(wave), T = TIERS[tier], code = waveCode(wave);
  const id = `fl${wave}`, clip = `clip-path="url(#${id}-art)"`;
  const c = 256;

  const stripeSvg = (fill: boolean) => STRIPE_C.slice(0, T.stripes).map((k) =>
    `<path d="M ${k + 400},-400 L ${k - 400},400" ${fill ? `stroke="${T.stripe}"` : ''} stroke-width="14" fill="none"/>`).join('');
  const rocks = SLOTS.slice(0, Math.min(wave - 1, SLOTS.length)).map(([x, y, r], i) => `<path d="${rockPath(x, y, r, i + 1)}"/>`).join('');
  const starSvg = Array.from({ length: stars }, (_, i) => {
    const a = (-90 + (i - (stars - 1) / 2) * 12.5) * (Math.PI / 180);
    return starPath(c + 238 * Math.cos(a), c + 238 * Math.sin(a), 16.5, (a * 180) / Math.PI + 90);
  }).join(' ');

  const rocketCol = `<g ${RK}><path d="${RKT.flame}" fill="${AMBER}"/><path d="${RKT.coreFlame}" fill="${CORE}"/>`
    + `<path d="${RKT.nozzles}" fill="${HULL_D}"/><path d="${RKT.boosters}" fill="${HULL_M}"/><path d="${RKT.core}" fill="${HULL_L}"/>`
    + `<path d="${RKT.inter}" fill="${HULL_D}"/><path d="${RKT.upper}" fill="${HULL_L}"/><path d="${RKT.fairing}" fill="${HULL_L}"/>`
    + `<path d="${RKT.band}" fill="${BLUE}"/></g>`;
  const rocketSil = `<g ${RK}>${(['flame', 'nozzles', 'boosters', 'core', 'inter', 'upper', 'fairing'] as const).map((k) => `<path d="${RKT[k]}"/>`).join('')}</g>`;
  const rocketCuts = `<g ${RK} fill="none" stroke-width="5"><path d="M -175,-18.5 L -31,-18.5 M -175,18.5 L -31,18.5 M 58,-15.5 V 15.5 M 76,-15.5 V 15.5 M 126,-19.5 V 19.5 M 133,-19.5 V 19.5"/></g>`;
  const rockSil = `<g ${HALF_N}><path d="${NEAR}"/></g><g ${HALF_F}><path d="${FAR}"/></g><path d="${CHIPS}"/>`;
  const halo = (svg: string, w: number) => `<g fill="none" stroke-width="${w}" stroke-linejoin="round">${svg}</g>`;

  const [, tw] = textPath(code, 25, 0.14);
  const tsize = Math.min(25, (25 * 286) / tw);
  const [txtS, twS] = textPath(code, tsize, 0.14);

  const layers: Layer[] = [
    { svg: `<circle cx="${c}" cy="${c}" r="230" fill="${T.field}"/>`, bit: 'skip' },
    { svg: `<g ${clip}>${stripeSvg(true)}</g>`, bit: 'ink', bitSvg: `<g ${clip}>${stripeSvg(false)}</g>` },
    { svg: `<circle cx="${c}" cy="${c}" r="238" fill="none" stroke="${T.ring}" stroke-width="16"/>`, bit: 'ink' },
    { svg: `<circle cx="${c}" cy="${c}" r="216" fill="none" stroke="${T.hair}" stroke-width="2" opacity=".6"/>`, bit: 'skip' },
    { svg: T.trim ? `<circle cx="${c}" cy="${c}" r="222" fill="none" stroke="${AMBER}" stroke-width="2.5"/>` : '', bit: 'skip' },
    { svg: CROSSES.map(([x, y, s]) => cross(x, y, s)).join(''), bit: 'skip' },
    // background contacts, then the target, each with a 1-bit halo so they read against the stripes
    { svg: '', bit: 'cut', bitSvg: halo(rocks, 6) },
    { svg: `<g fill="${HULL_D}">${rocks}</g>`, bit: 'ink', bitSvg: rocks },
    { svg: '', bit: 'cut', bitSvg: halo(rockSil, 10) },
    { svg: `<g ${HALF_N}><path d="${NEAR}" fill="${HULL_M}"/><g fill="${HULL_D}">${CRATERS_N}</g></g>`
      + `<g ${HALF_F}><path d="${FAR}" fill="${HULL_M}"/><g fill="${HULL_D}">${CRATERS_F}</g></g><path d="${CHIPS}" fill="${HULL_M}"/>`,
      bit: 'ink', bitSvg: rockSil },
    { svg: '', bit: 'cut', bitSvg: `<g ${HALF_N}>${CRATERS_N}</g><g ${HALF_F}>${CRATERS_F}</g>` },
    { svg: '', bit: 'cut', bitSvg: `<g ${clip}>${halo(rocketSil, 22)}</g>` },
    { svg: `<g ${clip}>${rocketCol}</g>`, bit: 'ink', bitSvg: `<g ${clip}>${rocketSil}</g>` },
    { svg: '', bit: 'cut', bitSvg: rocketCuts },
    { svg: `<path d="${BOLT}" stroke="${EMBER}" stroke-width="7" stroke-linecap="round" fill="none"/>`, bit: 'ink',
      bitSvg: `<path d="${BOLT}" stroke-width="7" stroke-linecap="round" fill="none"/>` },
    // stars embroidered on the ring: amber with an ink keyline in colour, knocked out of the ring in 1-bit
    { svg: `<path d="${starSvg}" fill="${AMBER}" stroke="${INK}" stroke-width="2.5" stroke-linejoin="round"/>`, bit: 'cut',
      bitSvg: `<path d="${starSvg}"/>` },
    { svg: `<g transform="translate(${f(c - twS / 2)} ${512 - 96})" fill="${HULL_L}">${txtS}</g>`, bit: 'ink' },
  ];

  const defs = `<clipPath id="${id}-art"><circle cx="${c}" cy="${c}" r="214"/></clipPath>`;
  const head = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512"><title>NYKO patch ${code}</title>`;
  const color = `${head}<defs>${defs}</defs>${layers.map((l) => l.svg).join('')}</svg>`;
  const strip = (s: string) => s.replace(/(fill|stroke)="(?!none)[^"]*"/g, '').replace(/(fill-|stroke-)?opacity="[^"]*"/g, '');
  const mask = layers.filter((l) => l.bit !== 'skip').map((l) => {
    const col = l.bit === 'cut' ? '#000' : '#fff';
    return `<g fill="${col}" stroke="${col}">${strip(l.bitSvg ?? l.svg)}</g>`;
  }).join('');
  const onebit = `${head}<defs>${defs}<mask id="${id}-m" maskUnits="userSpaceOnUse" x="0" y="0" width="512" height="512">${mask}</mask></defs>`
    + `<rect width="512" height="512" fill="#000" mask="url(#${id}-m)"/></svg>`;
  return { wave, code, tier, stars, color, onebit };
}
