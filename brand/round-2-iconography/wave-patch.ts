//   stars  = ((wave-1) % 5) + 1  embroidered on the top of the ring, one per wave inside a tier
//   tier   = min(floor((wave-1) / 5), 4); each tier changes field, ring and speed stripes:
//            T0 waves 1-5    ink field, slate ring, no stripes
//            T1 waves 6-10   ink field, slate ring, 1 stripe
//            T2 waves 11-15  ink field, light ring, 2 stripes
//            T3 waves 16-20  deep field, light ring, 3 blue stripes
//            T4 waves 21+    deep field, blue ring, 3 blue stripes, amber inner trim (the top rank; later waves keep it)
//   rocks  = min(wave-1, 8) small background contacts, filling in over the early waves
// The ember bolt is the patch's only ember element at every wave.

