const INK = '#1E2233', HULL_D = '#525C7A', HULL_M = '#9AA4BE', HULL_L = '#C9CFDE', HULL_XL = '#DDE2EC';
const DEEP = '#2A3170', BLUE = '#3238C9', EMBER = '#FF4A22', AMBER = '#FFB300', CORE = '#FFF3E0';

type Tier = { field: string; ring: string; hair: string; stripes: number; stripe: string; trim: boolean };
const TIERS: Tier[] = [
  { field: INK, ring: HULL_M, hair: HULL_L, stripes: 0, stripe: HULL_D, trim: false },
  { field: INK, ring: HULL_M, hair: HULL_L, stripes: 1, stripe: HULL_D, trim: false },
  { field: INK, ring: HULL_L, hair: HULL_L, stripes: 2, stripe: HULL_D, trim: false },
  { field: DEEP, ring: HULL_L, hair: HULL_L, stripes: 3, stripe: BLUE, trim: false },
  { field: DEEP, ring: BLUE, hair: HULL_XL, stripes: 3, stripe: BLUE, trim: true },
];
export const STARS_PER_TIER = 5;
export const TOP_TIER = TIERS.length - 1;

export function waveTier(wave: number): number {
  return Math.min(Math.floor((Math.max(1, wave) - 1) / STARS_PER_TIER), TOP_TIER);
}
export function waveStars(wave: number): number {
  return ((Math.max(1, wave) - 1) % STARS_PER_TIER) + 1;
}
export function waveCode(wave: number): string {
  return `FL-${String(wave).padStart(2, '0')} · WAVE ${wave}`;
}

