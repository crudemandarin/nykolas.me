#!/usr/bin/env python3
"""Bake the IBM Plex Mono glyphs that wave-patch codes use into wave-patch.ts (this folder).

Patches never contain <text>, and the site can't run fontTools, so the few glyphs a code like
"FL-07 · WAVE 7" needs are outlined here and written between the <glyphs> markers in the module.
Re-run only if CHARSET or the font changes.     python3 gen_wave_font.py   (needs fonttools)
"""
import os
import re

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.join(HERE, "wave-patch.ts")
CHARSET = "FL-0123456789 ·WAVE"

font = TTFont(os.path.join(HERE, "fonts", "IBMPlexMono-Medium.ttf"))
gs, cmap, upem = font.getGlyphSet(), font["cmap"].getBestCmap(), font["head"].unitsPerEm

rows = []
for ch in CHARSET:
    g = gs[cmap[ord(ch)]]
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:g}")
    g.draw(pen)
    rows.append(f"  {ch!r}: [{g.width}, '{pen.getCommands()}'],".replace('"', "'"))

block = (f"// <glyphs> generated by brand/round-2-iconography/gen_wave_font.py (IBM Plex Mono Medium, OFL)\n"
         f"const UPEM = {upem};\n"
         f"const GLYPHS: Record<string, [number, string]> = {{\n" + "\n".join(rows) + "\n};\n// </glyphs>")
src = open(MODULE).read()
src = re.sub(r"// <glyphs>.*?// </glyphs>", lambda _: block, src, flags=re.S)
open(MODULE, "w").write(src)
print(f"baked {len(CHARSET)} glyphs into {os.path.relpath(MODULE)}")
